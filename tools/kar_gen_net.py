"""Write runtime/ov_net.c: offline answers for a game's nn::socket and nn::ssl imports (C++ and C forms).

    .venv\\Scripts\\python tools\\kar_gen_net.py --exefs build\\extracted\\kar458752\\exefs --out runtime\\ov_net.c

Each import is classed by rule (see RULES) into an answer: setup succeeds, socket calls fail with -1 and ENETDOWN,
name lookups fail, SSL connections fail. Pure helpers (byte order, address text) stay with the lifted SDK. Symbols the
runtime already answers elsewhere are skipped. Symbol names only; no game code or data goes into the output.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'recomp'))
from nso import Nso  # noqa: E402

# (pattern on the symbol, answer); first match wins. None leaves the symbol to the lifted SDK.
RULES = [
    (r'Inet(Htons|Ntohs|Htonl|Ntohl|Pton|Ntop)|^inet_(pton|ntop)$|GAIStrError|CopyFromPlatform', None),
    (r'IsInitialized', 'net_true'),
    (r'GetLastErrno|GetLastError', 'net_errno'),
    (r'SetLastErrno|FreeAddrInfo', 'net_nothing'),
    (r'GetAddrInfo', 'net_gai_fail'),
    (r'(socket|ssl)\d*(Initialize|Finalize)|nnssl(Initialize|Finalize)|ssl7Context(C1|D1|6Create|7Destroy|15Import|9Import|19Register)|nnsslContext(Destroy|GetContextId)',
     'net_ok'),
    (r'ssl14BuiltInManager|nnsslConnection', 'net_ssl_fail'),
    (r'socket|nnsock', 'net_fail'),
]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--exefs', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args()
    imports = sorted({s[0] for s in Nso(str(args.exefs / 'main')).imports()})
    runtime = '\n'.join(p.read_text(encoding='utf-8', errors='replace') for p in (ROOT / 'runtime').rglob('*.c')
                        if p.name != args.out.name)
    runtime = re.sub(r'"\s*\n\s*"', '', runtime)
    net = [s for s in imports if re.search(r'^_ZN2nn(6socket|3ssl)|^nnsocket|^nnssl|^inet_', s)]
    rows, kept = [], []
    for s in net:
        if f'"{s}"' in runtime:
            continue
        answer = next((a for pat, a in RULES if re.search(pat, s)), 'net_fail')
        (rows if answer else kept).append((s, answer))
    out = [
        '// Offline answers for the game\'s nn::socket and nn::ssl imports. Generated by tools/kar_gen_net.py from the',
        '// main module\'s import list (symbol names only); edit the rules there, not this file.',
        '//',
        '// The host has no network: as on a console without a connection, setup succeeds and every connection fails.',
        '// Socket calls return -1 with ENETDOWN, name lookups fail, SSL connections fail. Kirby Air Riders reaches',
        '// nnsslInitialize at boot. Byte-order and address-text helpers stay with the lifted SDK (no service involved).',
        '',
        '#include <stdint.h>',
        '',
        '#include "host.h"',
        '',
        '#define NET_ENETDOWN 50                                    // Horizon BSD errno',
        '#define NET_EAI_FAIL 4                                     // getaddrinfo: non-recoverable failure',
        '#define NET_R_SSL_FAIL ((uint32_t)(123 | (1 << 9)))         // an ssl-module failure; only != 0 is tested',
        '',
        'static void net_ok(Cpu *c) { ret_x(c, 0); }',
        'static void net_true(Cpu *c) { ret_x(c, 1); }',
        'static void net_nothing(Cpu *c) { (void)c; }',
        'static void net_fail(Cpu *c) { ret_x(c, (uint64_t)(int64_t)-1); }',
        'static void net_errno(Cpu *c) { ret_x(c, NET_ENETDOWN); }',
        'static void net_gai_fail(Cpu *c) { ret_x(c, NET_EAI_FAIL); }',
        'static void net_ssl_fail(Cpu *c) { ret_x(c, NET_R_SSL_FAIL); }',
        '',
    ]
    for s, a in rows:
        out.append(f'HOST_OVERRIDE("{s}", {a});')
    out.append('')
    out.append(f'// Left to the lifted SDK ({len(kept)}): ' + ', '.join(s for s, _ in kept))
    args.out.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    from collections import Counter
    print(f'{args.out}: {len(rows)} answered', dict(Counter(a for _, a in rows)), f'{len(kept)} left to the SDK')


if __name__ == '__main__':
    main()
